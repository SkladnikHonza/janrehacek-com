(function initLang() {
    let lang = 'cs';
    try {
        const saved = localStorage.getItem('preferredLang');
        if (saved && translations[saved]) {
            lang = saved;
        } else {
            const browserLang = (navigator.language || 'cs').toLowerCase().split('-')[0];
            if (translations[browserLang]) lang = browserLang;
        }
    } catch(e) {}
    setLanguage(lang);
})();



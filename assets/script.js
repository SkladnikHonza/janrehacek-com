// Posuvnik s poctem klientu + volba planu → odhad provize.
// 20 % z prvni platby + 10 % z kazde dalsi (rok = prvni platba + 11x opakovana).
(function initPartnerCalc() {
    const range = document.getElementById('pcRange');
    if (!range) return;

    const elClients = document.getElementById('pcClients');
    const elYear    = document.getElementById('pcYear');
    const elFirst   = document.getElementById('pcFirst');
    const elMonth   = document.getElementById('pcMonth');
    const plans     = document.querySelectorAll('.partner-plan');

    const nf = new Intl.NumberFormat('cs-CZ');
    const kc = (n) => nf.format(Math.round(n)) + ' Kč';

    const activePlan = document.querySelector('.partner-plan.active');
    let price = activePlan ? parseInt(activePlan.getAttribute('data-price'), 10) : 599;

    function render() {
        const clients = parseInt(range.value, 10) || 0;
        const first = clients * price * 0.20;
        const month = clients * price * 0.10;
        if (elClients) elClients.textContent = clients;
        if (elFirst)   elFirst.textContent   = kc(first);
        if (elMonth)   elMonth.textContent   = kc(month);
        if (elYear)    elYear.textContent    = kc(first + month * 11);
    }

    range.addEventListener('input', render);
    plans.forEach(btn => {
        btn.addEventListener('click', () => {
            plans.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            price = parseInt(btn.getAttribute('data-price'), 10) || price;
            render();
        });
    });

    render();
})();
